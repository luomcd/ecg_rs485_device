void ecg_filter_f32_reset(ecg_filter_f32 *f)
{
    uint32_t i;
    if (!f) return;
    for (i = 0; i < ECG_NUM_SECTIONS; i++) {
        biquad_df2t_f32_reset(&f->s[i]);
    }
    /* 注意：reset 只清状态，**不改 notch_on、也不动 last_x**（复位≠关陷波）。
     * ★T48b：本函数会把陷波节也清零，但**此处无需 DC 预置**——唯一的调用方
     *   fast_restore_snippet.c 伪迹重同步路径会同时 ecg_dc_block_reset()，之后
     *   dc_block 首样本输出 0（warmed=0 ⇒ 从 0 起），故陷波节从零状态启动是自洽的。 */
}

float ecg_filter_f32_process(ecg_filter_f32 *f, float x)
{
    float y = x;
    uint32_t i;
    if (!f) return x;
    /* ★T48b：记住链输入（陷波节在链首 ⇒ 它就是陷波节的输入），供 set_notch 做 DC 预置。
     * 常态 notch_on=1 时本字段只写不读，热路径开销 = 1 次存储。 */
    f->last_x = x;
    /* 工频滤波器组旁路 = 链首 ECG_NUM_NOTCH_SECTIONS 节整段跳过（见 ecg_filter.h 顶部说明） */
    for (i = (f->notch_on ? 0u : (uint32_t)ECG_NUM_NOTCH_SECTIONS);
         i < ECG_NUM_SECTIONS; i++) {
        y = biquad_df2t_f32_process(&f->s[i], y);
    }
    return y;
}

void ecg_filter_f32_process_block(ecg_filter_f32 *f,
                                  const float *in, float *out, uint32_t n)
{
    uint32_t i;
    if (!f || !in || !out) return;
    for (i = 0; i < n; i++) {
        out[i] = ecg_filter_f32_process(f, in[i]);
    }
}


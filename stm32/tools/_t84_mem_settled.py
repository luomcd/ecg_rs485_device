def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry', action='store_true')
    a = ap.parse_args()

    txt = io.open(SETTLED, encoding='utf-8').read()
    before = len(txt)
    print('SETTLED.md 改前：%d 字符（限 5000，余 %d）' % (before, 5000 - before))
    print()

    bad = 0
    for old, new, label in EDITS:
        n = txt.count(old)
        ok = (n == 1)
        if not ok:
            bad += 1
        print('  %s %-34s 命中 %d 次  Δ=%+d' % ('✓' if ok else '✗', label, n, len(new) - len(old)))
        if ok and not a.dry:
            txt = txt.replace(old, new)
    print()

    after = len(txt)
    print('SETTLED.md 改后：%d 字符（余 %d）  Δ=%+d' % (after, 5000 - after, after - before))
    if bad:
        print('⇒ **有 %d 处没命中，未写盘**' % bad)
        return 1
    if a.dry:
        print('⇒ [dry] 未写盘')
        return 0
    io.open(SETTLED, 'w', encoding='utf-8', newline='\n').write(txt)
    print('⇒ 已写盘')
    return 0


if __name__ == '__main__':
    sys.exit(main())

def append_once(path, text, marker):
    s = io.open(path, encoding='utf-8').read()
    if marker in s:
        print('  已存在，跳过：%s' % os.path.basename(path))
        return
    if not s.endswith('\n'):
        s += '\n'
    io.open(path, 'w', encoding='utf-8', newline='\n').write(s + text)
    print('  追加 %+5d 字符：%s' % (len(text), os.path.basename(path)))



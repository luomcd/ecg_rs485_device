def patch(path, reps, cap, label):
    s = io.open(path, encoding='utf-8').read()
    n0 = len(s)
    print('--- %s（%d 字符，限 %d）---' % (label, n0, cap))
    # ★逐条**顺序**校验（后者可能依赖前面的替换结果 ⇒ 不能一次性预校验）
    for o, nn, t in reps:
        c = s.count(o)
        assert c == 1, '%s 未命中(%d 处)：%s' % (label, c, t)
        s = s.replace(o, nn)
        print('  %-16s %+5d' % (t, len(nn) - len(o)))
    assert len(s) <= cap, '%s 超限 %d（未写入）' % (label, len(s) - cap)
    io.open(path, 'w', encoding='utf-8', newline='\n').write(s)
    print('  ⇒ %d 字符（余 %d）' % (len(s), cap - len(s)))


